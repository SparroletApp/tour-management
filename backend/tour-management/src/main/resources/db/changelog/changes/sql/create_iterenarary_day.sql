CREATE TABLE tour_itinerary_days (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     tour_package_id BIGINT NOT NULL,

                                     day_number INTEGER NOT NULL,
                                     tour_date DATE,

                                     title VARCHAR(250),
                                     description TEXT,

                                     overnight_city VARCHAR(150),
                                     meal_plan VARCHAR(200),

                                     created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                     updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT fk_tour_itinerary_days_package
                                         FOREIGN KEY (tour_package_id)
                                             REFERENCES tour_packages(id)
                                             ON DELETE CASCADE
);

-- Index for fetching itinerary days by tour package
CREATE INDEX idx_tour_itinerary_days_package_id
    ON tour_itinerary_days(tour_package_id);

-- Index for maintaining day order
CREATE INDEX idx_tour_itinerary_days_day_number
    ON tour_itinerary_days(tour_package_id, day_number);

-- Index for filtering by tour date
CREATE INDEX idx_tour_itinerary_days_tour_date
    ON tour_itinerary_days(tour_date);