CREATE TABLE tour_optional_activitys (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                         tour_package_id BIGINT NOT NULL,

                                         activity_name VARCHAR(200) NOT NULL,
                                         description TEXT,

                                         price NUMERIC(12, 2) DEFAULT 0.00,
                                         currency VARCHAR(10) DEFAULT 'INR',

                                         availability_type VARCHAR(100),

                                         active BOOLEAN NOT NULL DEFAULT TRUE,

                                         created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                         updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                         CONSTRAINT fk_tour_optional_activitys_package
                                             FOREIGN KEY (tour_package_id)
                                                 REFERENCES tour_packages(id)
                                                 ON DELETE CASCADE
);

-- Index for fetching optional activities by tour package
CREATE INDEX idx_tour_optional_activitys_package_id
    ON tour_optional_activitys(tour_package_id);

-- Index for filtering activities by availability
CREATE INDEX idx_tour_optional_activitys_availability
    ON tour_optional_activitys(availability_type);

-- Index for active/inactive activities
CREATE INDEX idx_tour_optional_activitys_active
    ON tour_optional_activitys(active);