CREATE TABLE tour_destinations (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                   tour_package_id BIGINT NOT NULL,

                                   country_name VARCHAR(150) NOT NULL,
                                   city_name VARCHAR(150) NOT NULL,
                                   description TEXT,

                                   sequence_number INTEGER,

                                   created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                   updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Index for fetching destinations by tour package
CREATE INDEX idx_tour_destinations_package_id
    ON tour_destinations(tour_package_id);

-- Index for maintaining destination order
CREATE INDEX idx_tour_destinations_sequence
    ON tour_destinations(tour_package_id, sequence_number);