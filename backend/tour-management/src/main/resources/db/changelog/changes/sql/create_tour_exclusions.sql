CREATE TABLE tour_exclusions (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 tour_package_id BIGINT NOT NULL,

                                 description TEXT NOT NULL,

                                 sequence_number INTEGER,

                                 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Index for fetching exclusions by tour package
CREATE INDEX idx_tour_exclusions_package_id
    ON tour_exclusions(tour_package_id);

-- Index for maintaining exclusion order
CREATE INDEX idx_tour_exclusions_sequence
    ON tour_exclusions(tour_package_id, sequence_number);

-- Foreign key to tour_packages
ALTER TABLE tour_exclusions
    ADD CONSTRAINT fk_tour_exclusions_package
        FOREIGN KEY (tour_package_id)
            REFERENCES tour_packages(id)
            ON DELETE CASCADE;