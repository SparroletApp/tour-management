CREATE TABLE tour_flights (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              tour_package_id BIGINT NOT NULL,

                              flight_type VARCHAR(50),
                              airline_name VARCHAR(150),
                              flight_number VARCHAR(50),

                              departure_airport VARCHAR(150),
                              arrival_airport VARCHAR(150),

                              departure_date_time TIMESTAMP,
                              arrival_date_time TIMESTAMP,

                              baggage_allowance VARCHAR(100),
                              cabin_baggage VARCHAR(100),

                              remarks TEXT,

                              created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_tour_flights_package
                                  FOREIGN KEY (tour_package_id)
                                      REFERENCES tour_packages(id)
                                      ON DELETE CASCADE
);

-- Index for fetching flights by tour package
CREATE INDEX idx_tour_flights_package_id
    ON tour_flights(tour_package_id);

-- Index for filtering flights by departure date
CREATE INDEX idx_tour_flights_departure_date
    ON tour_flights(departure_date_time);