CREATE TABLE tour_hotels (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             tour_package_id BIGINT NOT NULL,

                             city_name VARCHAR(150),
                             hotel_name VARCHAR(200),
                             hotel_category VARCHAR(100),

                             check_in_date DATE,
                             check_out_date DATE,
                             number_of_nights INTEGER,

                             address TEXT,
                             contact_number VARCHAR(30),
                             remarks TEXT,

                             created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_tour_hotels_package
                                 FOREIGN KEY (tour_package_id)
                                     REFERENCES tour_packages(id)
                                     ON DELETE CASCADE
);

-- Index for fetching hotels by tour package
CREATE INDEX idx_tour_hotels_package_id
    ON tour_hotels(tour_package_id);

-- Index for filtering hotels by city
CREATE INDEX idx_tour_hotels_city
    ON tour_hotels(city_name);

-- Index for filtering by check-in date
CREATE INDEX idx_tour_hotels_checkin
    ON tour_hotels(check_in_date);