CREATE TABLE tour_inclusions (
                                 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                 tour_package_id BIGINT NOT NULL,

                                 description TEXT NOT NULL,

                                 sequence_number INTEGER,

                                 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                 CONSTRAINT fk_tour_inclusions_package
                                     FOREIGN KEY (tour_package_id)
                                         REFERENCES tour_packages(id)
                                         ON DELETE CASCADE
);

-- Index for fetching inclusions by tour package
CREATE INDEX idx_tour_inclusions_package_id
    ON tour_inclusions(tour_package_id);

-- Index for maintaining inclusion order
CREATE INDEX idx_tour_inclusions_sequence
    ON tour_inclusions(tour_package_id, sequence_number);