CREATE TABLE tour_itinerary_activitys (
                                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                          itinerary_day_id BIGINT NOT NULL,

                                          activity_name VARCHAR(200) NOT NULL,
                                          description TEXT,

                                          activity_type VARCHAR(100),

                                          included BOOLEAN DEFAULT FALSE,
                                          optional BOOLEAN DEFAULT FALSE,

                                          sequence_number INTEGER,

                                          additional_price NUMERIC(12, 2) DEFAULT 0.00,
                                          currency VARCHAR(10) DEFAULT 'INR',

                                          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                          updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                          CONSTRAINT fk_tour_activity_itinerary_day
                                              FOREIGN KEY (itinerary_day_id)
                                                  REFERENCES tour_itinerary_days(id)
                                                  ON DELETE CASCADE
);

-- Index for fetching activities by itinerary day
CREATE INDEX idx_tour_activity_itinerary_day_id
    ON tour_itinerary_activitys(itinerary_day_id);

-- Index for maintaining activity order
CREATE INDEX idx_tour_activity_sequence
    ON tour_itinerary_activitys(itinerary_day_id, sequence_number);

-- Index for filtering activity types
CREATE INDEX idx_tour_activity_type
    ON tour_itinerary_activitys(activity_type);