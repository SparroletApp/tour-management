CREATE TABLE tour_medias (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             tour_package_id BIGINT NOT NULL,

                             media_type VARCHAR(50),
                             file_name VARCHAR(255),
                             file_url TEXT,
                             caption TEXT,

                             sequence_number INTEGER,

                             created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                             updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT fk_tour_medias_package
                                 FOREIGN KEY (tour_package_id)
                                     REFERENCES tour_packages(id)
                                     ON DELETE CASCADE
);

-- Index for fetching media by tour package
CREATE INDEX idx_tour_medias_package_id
    ON tour_medias(tour_package_id);

-- Index for maintaining media order
CREATE INDEX idx_tour_medias_sequence
    ON tour_medias(tour_package_id, sequence_number);

-- Index for filtering media types
CREATE INDEX idx_tour_medias_type
    ON tour_medias(media_type);