CREATE TABLE tour_packages (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               tour_code VARCHAR(100) NOT NULL UNIQUE,
                               tour_name VARCHAR(255) NOT NULL,
                               description TEXT,

                               duration_days INTEGER,
                               duration_nights INTEGER,

                               minimum_travellers INTEGER,
                               maximum_travellers INTEGER,

                               currency VARCHAR(10) DEFAULT 'INR',
                               status VARCHAR(50) DEFAULT 'DRAFT',

                               start_date DATE,
                               end_date DATE,

                               cover_image_url TEXT,

                               created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                               updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Index for searching tours by name
CREATE INDEX idx_tour_packages_name
    ON tour_packages(tour_name);

-- Index for filtering tours by status
CREATE INDEX idx_tour_packages_status
    ON tour_packages(status);

-- Index for filtering tours by start date
CREATE INDEX idx_tour_packages_start_date
    ON tour_packages(start_date);

-- Index for filtering tours by date range
CREATE INDEX idx_tour_packages_date_range
    ON tour_packages(start_date, end_date);