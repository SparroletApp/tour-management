CREATE TABLE tour_price_rules (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                  tour_package_id BIGINT NOT NULL,

                                  passenger_category VARCHAR(100),
                                  room_category VARCHAR(100),

                                  price NUMERIC(12, 2) NOT NULL,
                                  currency VARCHAR(10) DEFAULT 'INR',

                                  valid_from DATE,
                                  valid_until DATE,

                                  remarks TEXT,

                                  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                                  CONSTRAINT fk_tour_price_rules_package
                                      FOREIGN KEY (tour_package_id)
                                          REFERENCES tour_packages(id)
                                          ON DELETE CASCADE
);

-- Index for fetching price rules by tour package
CREATE INDEX idx_tour_price_rules_package_id
    ON tour_price_rules(tour_package_id);

-- Index for filtering passenger categories
CREATE INDEX idx_tour_price_rules_passenger_category
    ON tour_price_rules(passenger_category);

-- Index for filtering room categories
CREATE INDEX idx_tour_price_rules_room_category
    ON tour_price_rules(room_category);

-- Index for checking price validity
CREATE INDEX idx_tour_price_rules_validity
    ON tour_price_rules(valid_from, valid_until);